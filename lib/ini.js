'use strict';
/*
 * php.ini and my.ini helpers. PURE (no I/O): callers read and write the files.
 */
const path = require('path');

const win = path.win32;

/** Value without surrounding quotes; for unquoted values an inline ";" comment is removed. */
function parseIniValue(raw) {
  let v = String(raw == null ? '' : raw).trim();
  if (v.startsWith('"') || v.startsWith("'")) {
    const q = v[0];
    const end = v.indexOf(q, 1);
    return end > 0 ? v.slice(1, end) : v.slice(1);
  }
  const semi = v.indexOf(';');
  if (semi >= 0) v = v.slice(0, semi);
  return v.trim();
}

/** Last non-commented value of `key` in php.ini text, or null. */
function getPhpIniValue(text, key) {
  if (typeof text !== 'string' || !key) return null;
  const want = String(key).trim().toLowerCase();
  let found = null;
  for (const line of text.replace(/^﻿/, '').split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t[0] === ';' || t[0] === '#' || t[0] === '[') continue;
    const m = /^([^=]+?)\s*=\s*(.*)$/.exec(t);
    if (!m) continue;
    if (m[1].trim().toLowerCase() !== want) continue;
    found = parseIniValue(m[2]);
  }
  return found;
}

function isAbsolute(p) {
  return /^[A-Za-z]:[\\/]/.test(p) || /^[\\/]{2}[^\\/]/.test(p);
}

/**
 * The folder the php.ini was written for: when extension_dir is absolute and ends with
 * \ext or /ext, its parent folder; otherwise null. The caller compares it with the real PHP dir.
 */
function detectIniHome(iniText, phpDir) { // eslint-disable-line no-unused-vars
  const ext = getPhpIniValue(iniText, 'extension_dir');
  if (!ext) return null;
  const v = ext.trim();
  if (!isAbsolute(v)) return null;
  const m = /^(.*?)[\\/]+ext[\\/]*$/i.exec(v);
  if (!m || !m[1]) return null;
  return m[1];
}

function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Rewrites every occurrence of fromHome (case-insensitive, "\" or "/" spelling) that is followed
 * by a path boundary to toDir, keeping the separator style of each occurrence. A longer folder
 * name that merely starts with fromHome (e.g. "...\php8.2" for "...\php") is never touched.
 */
function relocatePhpIni(iniText, fromHome, toDir, sourcePath) {
  const text = String(iniText == null ? '' : iniText);
  const from = String(fromHome || '').trim().replace(/[\\/]+$/, '');
  const to = String(toDir || '').trim().replace(/[\\/]+$/, '');
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const source = sourcePath ? String(sourcePath) : `${to.replace(/\//g, '\\')}\\php.ini`;
  const header = `; generated by PHP Station from ${source} (relocated ${from} -> ${to})${eol}`;
  if (!from || !to) return header + text;
  const pattern = from.split(/[\\/]+/).map(escapeRegex).join('[\\\\/]+');
  const re = new RegExp(`${pattern}(?=[\\\\/"'\\s;]|$)`, 'gim');
  const out = text.replace(re, (match) => {
    const slash = match.includes('/') ? '/' : (match.includes('\\') ? '\\' : null);
    if (slash === '/') return to.replace(/\\/g, '/');
    if (slash === '\\') return to.replace(/\//g, '\\');
    return to;
  });
  return header + out;
}

function myIniValue(raw) {
  let v = String(raw == null ? '' : raw).trim();
  if (v.startsWith('"') || v.startsWith("'")) {
    const q = v[0];
    const end = v.indexOf(q, 1);
    return end > 0 ? v.slice(1, end) : v.slice(1);
  }
  const hash = v.search(/\s[#;]/);
  if (hash >= 0) v = v.slice(0, hash);
  return v.trim();
}

function tidy(p) {
  let s = String(p).replace(/\//g, '\\');
  try { s = win.normalize(s); } catch { /* keep */ }
  while (s.length > 3 && s.endsWith('\\')) s = s.slice(0, -1);
  return s;
}

/**
 * Server settings from my.ini text: the [mysqld], [server], [mariadb] and [mariadbd] sections
 * (later values win). Keys may use "-" or "_". Relative datadir is resolved against basedir (or
 * the ini's folder), a relative log_error against the datadir.
 */
function parseMyIni(text, iniPath) {
  const res = { port: null, datadir: null, basedir: null, logError: null, bindAddress: null };
  const wanted = new Set(['mysqld', 'server', 'mariadb', 'mariadbd']);
  let section = '';
  let port = null;
  let datadir = null;
  let basedir = null;
  let logError = null;
  let bindAddress = null;
  for (const rawLine of String(text == null ? '' : text).replace(/^﻿/, '').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line[0] === '#' || line[0] === ';') continue;
    const sec = /^\[\s*([^\]]*?)\s*\]/.exec(line);
    if (sec) { section = sec[1].toLowerCase(); continue; }
    if (!wanted.has(section)) continue;
    if (line[0] === '!') continue;
    const m = /^([A-Za-z0-9_.-]+)\s*(?:=\s*(.*))?$/.exec(line);
    if (!m) continue;
    const key = m[1].toLowerCase().replace(/-/g, '_');
    const val = m[2] === undefined ? null : myIniValue(m[2]);
    switch (key) {
      case 'port': {
        const n = Number.parseInt(val, 10);
        port = Number.isInteger(n) && n > 0 && n < 65536 ? n : null;
        break;
      }
      case 'datadir': datadir = val || null; break;
      case 'basedir': basedir = val || null; break;
      case 'log_error': logError = val || null; break;
      case 'bind_address': bindAddress = val || null; break;
      default: break;
    }
  }
  const iniDir = iniPath ? win.dirname(String(iniPath).replace(/\//g, '\\')) : null;
  if (basedir) {
    basedir = tidy(basedir);
    if (!isAbsolute(basedir) && iniDir) basedir = tidy(win.resolve(iniDir, basedir));
  }
  if (datadir) {
    datadir = tidy(datadir);
    if (!isAbsolute(datadir)) {
      const base = basedir && isAbsolute(basedir) ? basedir : iniDir;
      if (base) datadir = tidy(win.resolve(base, datadir));
    }
  }
  if (logError) {
    logError = tidy(logError);
    if (!isAbsolute(logError)) {
      const base = datadir && isAbsolute(datadir) ? datadir : iniDir;
      if (base) logError = tidy(win.resolve(base, logError));
    }
  }
  res.port = port;
  res.datadir = datadir;
  res.basedir = basedir;
  res.logError = logError;
  res.bindAddress = bindAddress;
  return res;
}

module.exports = { parseIniValue, getPhpIniValue, detectIniHome, relocatePhpIni, parseMyIni };
