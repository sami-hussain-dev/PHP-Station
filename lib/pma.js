'use strict';
/*
 * phpMyAdmin inside PHP Station.
 *  - PHP Station runs its OWN copy in <tool>\runtimes\phpmyadmin\<version>: installed from
 *    phpmyadmin.net by the installer (SHA-256 checked), or copied from a phpMyAdmin that XAMPP /
 *    Laragon / WAMP already has (their folders are only read, never changed).
 *  - config.inc.php of that copy is written by PHP Station: one server per DB server entry
 *    (127.0.0.1 + its port), cookie login (passwords are typed in phpMyAdmin, never stored here).
 *  - It is served by a PHP built-in server on 127.0.0.1 (a PHP with mysqli, < 8.4 preferred).
 */
const fs = require('fs');
const path = require('path');
const util = require('./util');
const semver = require('./semver');
const procs = require('./procs');
const ports = require('./ports');
const runtimes = require('./runtimes');
const dbservers = require('./dbservers');
const envfile = require('./envfile');
const { tr } = require('./i18n');

const { AppError } = util;
const win = path.win32;

function pmaRoot(ctx) {
  return path.join(runtimes.toolRuntimesDir(ctx), 'phpmyadmin');
}
function dataDirOf(ctx) {
  return util.ensureDir(path.join(ctx.dataDir, 'phpmyadmin'));
}

// ------------------------------------------------------------------------------------------ detection

/** Version of a phpMyAdmin folder (package.json, else libraries/classes/Version.php), or null. */
function versionOf(dir) {
  const pj = util.readJson(win.join(dir, 'package.json'), null);
  if (pj && /^\d+\.\d+\.\d+/.test(String(pj.version || ''))) return String(pj.version).match(/^\d+\.\d+\.\d+/)[0];
  const txt = util.readText(win.join(dir, 'libraries', 'classes', 'Version.php'), '') || '';
  const m = /VERSION\s*=\s*'(\d+\.\d+\.\d+)/.exec(txt);
  return m ? m[1] : null;
}

function isPmaDir(dir) {
  return util.existsFile(win.join(dir, 'index.php')) && util.existsDir(win.join(dir, 'libraries')) && !!versionOf(dir);
}

/** phpMyAdmin folders that XAMPP / Laragon / WAMP already have (read-only sources for a copy). */
function detectLocal(ctx) {
  const out = [];
  const seen = new Set();
  const add = (dir) => {
    const k = util.normPath(dir);
    if (seen.has(k) || !isPmaDir(dir)) return;
    seen.add(k);
    out.push({ path: util.cleanPath(dir), version: versionOf(dir), stack: /laragon/i.test(dir) ? 'Laragon' : /wamp/i.test(dir) ? 'WAMP' : /xampp/i.test(dir) ? 'XAMPP' : 'Local' });
  };
  for (const root of ctx.store.data.settings.runtimeRoots || []) {
    const r = util.cleanPath(root);
    add(win.join(r, 'phpMyAdmin'));
    add(win.join(r, 'phpmyadmin'));
    add(win.join(r, 'etc', 'apps', 'phpMyAdmin'));
    for (const name of util.listDirNames(win.join(r, 'apps'))) if (/^phpmyadmin/i.test(name)) add(win.join(r, 'apps', name));
  }
  return out.sort((a, b) => semver.compare(b.version, a.version));
}

/** PHP Station's own copies, newest first: [{version, dir}]. */
function installed(ctx) {
  const root = pmaRoot(ctx);
  return util.listDirNames(root)
    .filter((n) => /^\d+\.\d+\.\d+$/.test(n) && isPmaDir(win.join(root, n)))
    .map((n) => ({ version: n, dir: win.join(root, n) }))
    .sort((a, b) => semver.compare(b.version, a.version));
}

/** PHP to serve phpMyAdmin: mysqli loaded, >= 7.2.5; below 8.4 preferred (phpMyAdmin 5.2 support). PURE. */
function choosePhp(phpList) {
  const ok = (phpList || []).filter((p) => p && p.ok && p.version && Array.isArray(p.extensions) && p.extensions.includes('mysqli')
    && semver.compare(p.version, '7.2.5') >= 0);
  const sorted = ok.slice().sort((a, b) => semver.compare(b.version, a.version));
  return sorted.find((p) => semver.compare(p.version, '8.4.0') < 0) || sorted[0] || null;
}

// ------------------------------------------------------------------------------------------ config (PURE)

function phpStr(s) {
  return `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/**
 * config.inc.php text. servers: [{label, port}] (index i+1 in phpMyAdmin). Cookie login,
 * no password stored, empty root password allowed (XAMPP / Laragon default).
 */
function buildConfig({ servers, secret, tempDir }) {
  const L = [
    '<?php',
    '/* Generated by PHP Station on every open — changes here are overwritten. */',
    `$cfg['blowfish_secret'] = ${phpStr(secret)};`,
    `$cfg['TempDir'] = ${phpStr(tempDir)};`,
    "$cfg['VersionCheck'] = false;",
    "$cfg['SendErrorReports'] = 'never';",
    "$cfg['ShowPhpInfo'] = false;",
    "$cfg['PmaNoRelation_DisableWarning'] = true;",
    "$cfg['LoginCookieValidity'] = 86400;",
    "$cfg['ExecTimeLimit'] = 600;",
    "$cfg['ServerDefault'] = 1;",
    '$i = 0;',
  ];
  for (const s of servers) {
    L.push('$i++;');
    L.push(`$cfg['Servers'][$i]['verbose'] = ${phpStr(s.label)};`);
    L.push("$cfg['Servers'][$i]['host'] = '127.0.0.1';");
    L.push(`$cfg['Servers'][$i]['port'] = ${phpStr(String(s.port))};`);
    L.push("$cfg['Servers'][$i]['connect_type'] = 'tcp';");
    L.push("$cfg['Servers'][$i]['auth_type'] = 'cookie';");
    L.push("$cfg['Servers'][$i]['AllowNoPassword'] = true;");
    L.push("$cfg['Servers'][$i]['compress'] = false;");
  }
  return `${L.join('\r\n')}\r\n`;
}

function secretOf(ctx) {
  const f = path.join(dataDirOf(ctx), 'secret.txt');
  let s = (util.readText(f, '') || '').trim();
  if (!/^[0-9a-f]{32}$/.test(s)) {
    s = util.randomHex(16);
    fs.writeFileSync(f, s);
  }
  return s;
}

/** Server list for the config: every DB server entry, plus `extra` ports (e.g. a Laragon server found by datadir). */
function serverList(ctx, extra = []) {
  const list = [];
  const seenPorts = new Set();
  for (const e of dbservers.buildEntries(ctx)) {
    // phpMyAdmin shows ":port" next to the name itself
    list.push({ id: e.id, label: e.label, port: e.effectivePort });
    seenPorts.add(e.effectivePort);
  }
  for (const x of extra) if (!seenPorts.has(x.port)) { list.push({ id: null, label: x.label, port: x.port }); seenPorts.add(x.port); }
  return list;
}

// ------------------------------------------------------------------------------------------ server

function state(ctx) {
  return ctx.store.data.pma && typeof ctx.store.data.pma === 'object' ? ctx.store.data.pma : null;
}

/** {running, pid, port, url, version, phpVersion} of the phpMyAdmin server. */
async function serverStatus(ctx, snap) {
  const st = state(ctx);
  if (!st || !st.pid) return { running: false };
  const s = snap || await procs.getSnapshot({ fresh: true });
  const p = s.procs.find((x) => x.pid === Number(st.pid));
  const listening = s.listeners.some((l) => l.port === st.port && l.pid === Number(st.pid));
  if (!p || p.name !== 'php.exe' || !listening) return { running: false };
  return { running: true, pid: st.pid, port: st.port, url: `http://127.0.0.1:${st.port}/`, version: st.version, phpVersion: st.phpVersion };
}

async function ensureServer(ctx, pma, php) {
  const cur = await serverStatus(ctx);
  const st = state(ctx);
  if (cur.running && st && util.samePath(st.dir, pma.dir) && util.samePath(st.phpPath, php.path)) return cur;
  if (cur.running) await stop(ctx);
  const snap = await procs.getSnapshot({ fresh: true });
  const s = ctx.store.data.settings;
  const reserved = (ctx.store.data.projects || []).map((p) => p.port);
  const busy = snap.listeners.map((l) => l.port);
  const preferred = st && Number.isInteger(st.port) ? st.port : s.webPortRange[1];
  const port = ports.pickPort({ from: s.webPortRange[0], to: s.webPortRange[1], preferred, reserved, busy });
  if (!port) throw new AppError('NO_PORT', tr('pma.noPort'), 409);
  const pdir = dataDirOf(ctx);
  const sessions = util.ensureDir(path.join(pdir, 'sessions'));
  const inv = runtimes.phpInvocation(php);
  const args = [...inv.preArgs,
    '-d', 'display_errors=0', '-d', 'error_reporting=E_ALL & ~E_DEPRECATED & ~E_USER_DEPRECATED & ~E_NOTICE',
    '-d', `session.save_path=${sessions}`, '-d', 'session.gc_maxlifetime=86400', '-d', 'memory_limit=1G', '-d', 'max_execution_time=600',
    '-d', 'upload_max_filesize=1G', '-d', 'post_max_size=1G',
    '-S', `127.0.0.1:${port}`, '-t', pma.dir];
  const logFile = path.join(ctx.dataDir, 'logs', 'phpmyadmin.log');
  util.ensureDir(path.dirname(logFile));
  util.rotateIfLarge(logFile);
  fs.appendFileSync(logFile, `===== ${util.nowIso()} phpMyAdmin ${pma.version} PHP ${php.version} port ${port} =====\r\n`);
  const pid = procs.spawnDetached(inv.file, args, { cwd: pma.dir, env: util.cleanEnv({ prependPath: [php.dir] }), logFile });
  if (!pid) throw new AppError('START_FAILED', tr('pma.startFailed'), 500);
  const ok = await ports.waitForPort(port, { timeoutMs: 15000, intervalMs: 200, isAlive: () => procs.pidExists(pid) });
  procs.invalidateCaches();
  if (!ok) {
    if (procs.pidExists(pid)) await procs.killTree(pid);
    throw new AppError('START_FAILED', tr('pma.startFailed'), 500, { logTail: util.tailFile(logFile, 30).text });
  }
  ctx.store.data.pma = { pid, port, dir: pma.dir, version: pma.version, phpPath: php.path, phpVersion: php.version, startedAt: util.nowIso() };
  ctx.store.save();
  ctx.log(`spawn phpmyadmin ${pma.version} pid ${pid} PHP ${php.version} port ${port}`);
  return { running: true, pid, port, url: `http://127.0.0.1:${port}/`, version: pma.version, phpVersion: php.version };
}

async function stop(ctx) {
  const st = state(ctx);
  if (!st || !st.pid) return { ok: true, wasRunning: false };
  const snap = await procs.getSnapshot({ fresh: true });
  const p = snap.procs.find((x) => x.pid === Number(st.pid));
  // only our own php -S on the remembered port
  const ours = !!(p && p.name === 'php.exe' && p.cmd && p.cmd.includes(`127.0.0.1:${st.port}`)
    && st.dir && p.cmd.toLowerCase().includes(util.normPath(st.dir)));
  if (ours) {
    const k = await procs.killTree(p.pid);
    ctx.log(`kill phpmyadmin pid ${p.pid}: ${k.ok}`);
    await ports.waitForPortClosed(st.port, { timeoutMs: 5000 });
  }
  ctx.store.data.pma = Object.assign({}, st, { pid: null });
  ctx.store.save();
  procs.invalidateCaches();
  return { ok: true, wasRunning: !!ours };
}

// ------------------------------------------------------------------------------------------ open

/** The DB server a request means: its own entry when running, else a server on the same data, else started. */
async function resolveDb(ctx, entry, projectId) {
  const snap = await procs.getSnapshot({ fresh: true });
  const st = dbservers.entryStatus(ctx, entry, snap);
  if (st.status === 'running') return { port: entry.effectivePort, label: entry.label, note: null };
  const other = await dbservers.findDatadirServer(ctx, entry, snap, { projectId });
  if (other) return { port: other.port, label: other.label, note: tr('note.dbUsingRunning', { label: other.label, port: other.port }) };
  if (ctx.store.data.settings.autoStartDb === false) {
    throw new AppError('DB_STOPPED', tr('err.dbStopped', { label: entry.label }), 409, { dbServerId: entry.id });
  }
  await dbservers.startServer(ctx, entry.id, {});
  return { port: entry.effectivePort, label: entry.label, note: tr('note.dbAutoStarted', { label: entry.label, port: entry.effectivePort }) };
}

/**
 * POST /api/pma/open {dbServerId?, projectId?} -> {url, port, note?, database?}.
 * PMA_MISSING (409, with the local copies that can be used) when PHP Station has no phpMyAdmin yet.
 */
async function open(ctx, body) {
  const b = body || {};
  const have = installed(ctx);
  if (!have.length) throw new AppError('PMA_MISSING', tr('pma.missing'), 409, { local: detectLocal(ctx) });
  const php = choosePhp(runtimes.getCache(ctx).php);
  if (!php) throw new AppError('PMA_NO_PHP', tr('pma.noPhp'), 409);
  const pma = have[0];

  let entry = null;
  let database = null;
  const projectId = typeof b.projectId === 'string' && b.projectId ? b.projectId : null;
  if (projectId) {
    const p = (ctx.store.data.projects || []).find((x) => x.id === projectId);
    if (!p) throw new AppError('NOT_FOUND', tr('err.projectNotFound'), 404);
    const env = envfile.parseEnv(util.readText(win.join(p.path, '.env'), '') || '');
    if (env.DB_DATABASE && /^[A-Za-z0-9_$-]{1,64}$/.test(env.DB_DATABASE)) database = env.DB_DATABASE;
    if (p.dbServerId) entry = dbservers.getEntry(ctx, p.dbServerId);
  }
  if (!entry && typeof b.dbServerId === 'string' && b.dbServerId) entry = dbservers.getEntry(ctx, b.dbServerId);

  let target = null;
  if (entry) target = await resolveDb(ctx, entry, projectId);
  const servers = serverList(ctx, target ? [target] : []);
  const idx = target ? servers.findIndex((s) => s.port === target.port) + 1 : 0;
  const tempDir = util.ensureDir(path.join(dataDirOf(ctx), 'tmp'));
  fs.writeFileSync(win.join(pma.dir, 'config.inc.php'), buildConfig({ servers, secret: secretOf(ctx), tempDir }));

  const srv = await ensureServer(ctx, pma, php);
  let url = `${srv.url}index.php`;
  const q = [];
  if (idx > 0) q.push(`server=${idx}`);
  if (database) q.push(`db=${encodeURIComponent(database)}`);
  if (q.length) url += `?${q.join('&')}`;
  return { url, port: srv.port, version: pma.version, phpVersion: srv.phpVersion, database, note: target ? target.note : null };
}

/** GET /api/pma -> {installed, local, server, php}. */
async function info(ctx) {
  const php = choosePhp(runtimes.getCache(ctx).php);
  return {
    installed: installed(ctx),
    local: detectLocal(ctx),
    server: await serverStatus(ctx),
    php: php ? { version: php.version, path: php.path } : null,
    root: pmaRoot(ctx),
  };
}

// ------------------------------------------------------------------------------------------ copy a local phpMyAdmin

/** Job: copies a DETECTED local phpMyAdmin into runtimes\phpmyadmin\<version> (without its config.inc.php). */
async function copyLocalJob(ctx, srcPath, log) {
  const src = detectLocal(ctx).find((x) => util.samePath(x.path, srcPath));
  if (!src) throw new AppError('BAD_INPUT', tr('pma.notDetected'), 400);
  const target = win.join(pmaRoot(ctx), src.version);
  if (fs.existsSync(target)) throw new AppError('EXISTS', tr('inst.exists', { path: target }), 409);
  const tmp = win.join(util.ensureDir(path.join(runtimes.toolRuntimesDir(ctx), '_tmp')), `pma-${src.version}-${util.randomHex(3)}`);
  log('info', tr('pma.copying', { from: src.path, to: target }));
  try {
    fs.cpSync(src.path, tmp, {
      recursive: true,
      // the source's own settings (passwords, its server) and its temp folder are not copied
      filter: (p) => !(util.samePath(p, win.join(src.path, 'config.inc.php')) || util.samePath(p, win.join(src.path, 'tmp'))),
    });
    util.ensureDir(path.dirname(target));
    fs.renameSync(tmp, target);
  } catch (e) {
    try { fs.rmSync(tmp, { recursive: true, force: true }); } catch { /* best effort */ }
    throw new AppError('COPY_FAILED', tr('pma.copyFailed', { message: e.message }), 500);
  }
  log('ok', tr('inst.installed', { path: target }));
  return { version: src.version, path: target, from: src.path };
}

